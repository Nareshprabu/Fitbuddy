# Scenario 2: Feedback-Based Workout Plan Updater (Gemini 1.5 Pro)
# ==============================================================================

@app.post("/api/regenerate-plan")
def api_regenerate_plan(req: RegeneratePlanRequest, request: Request):
    """
    Scenario 2:
    Takes existing workout plan ID and user feedback (e.g. 'more cardio', 'include rest days')
    and regenerates an updated plan using Gemini 1.5 Pro with version incrementation.
    """
    client_api_key = request.headers.get("x-gemini-api-key") or None

    current_plan = database.get_workout_plan(req.plan_id)
    if not current_plan:
        raise HTTPException(status_code=404, detail="Plan not found")

    user = database.get_user(current_plan["user_id"])
    if not user:
        raise HTTPException(status_code=404, detail="User associated with plan not found")

    # Save feedback into SQLite
    database.save_plan_feedback(plan_id=req.plan_id, feedback_text=req.feedback_text)

    # Regenerate plan using Gemini 1.5 Pro
    updated_plan_content = gemini_service.regenerate_workout_plan_with_feedback(
        current_plan=current_plan,
        feedback_text=req.feedback_text,
        user_info=user,
        api_key=client_api_key
    )

    new_version = current_plan["version"] + 1

    # Save as new version in SQLite
    new_plan_id = database.save_workout_plan(
        user_id=user["id"],
        title=updated_plan_content.get("title", f"Refined Plan v{new_version}"),
        summary=updated_plan_content.get("summary", ""),
        goal=user["goal"],
        intensity=user["intensity"],
        plan_data=updated_plan_content,
        version=new_version,
        model_used=updated_plan_content.get("model_used", gemini_service.MODEL_WORKOUT_GEN)
    )

    feedback_history = database.get_plan_feedback_history(req.plan_id)

    return {
        "status": "success",
        "message": f"Plan refined successfully to version {new_version}",
        "previous_plan_id": req.plan_id,
        "new_plan_id": new_plan_id,
        "version": new_version,
        "user_id": user["id"],
        "model_used": updated_plan_content.get("model_used", gemini_service.MODEL_WORKOUT_GEN),
        "plan": updated_plan_content,
        "feedback_applied": req.feedback_text,
        "feedback_history": feedback_history
    }

