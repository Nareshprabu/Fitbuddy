# Scenario 1: Personalized 7-Day Workout Plan Generator (Gemini 1.5 Pro)
# ==============================================================================

@app.post("/api/generate-plan")
def api_generate_plan(req: GeneratePlanRequest, request: Request):
    """
    Scenario 1:
    Inputs: Name, Age, Weight, Goal, Workout Intensity, Equipment, Notes.
    Outputs: Tailored 7-day schedule generated by Gemini 1.5 Pro and stored in SQLite.
    """
    try:
        client_api_key = request.headers.get("x-gemini-api-key") or None

        # 1. Save or retrieve user in SQLite
        user_id = database.save_user(
            name=req.name,
            age=req.age,
            weight=req.weight,
            goal=req.goal,
            intensity=req.intensity,
            equipment=req.equipment or "all",
            weight_unit=req.weight_unit or "kg",
            notes=req.notes or ""
        )

        # 2. Generate 7-day workout plan using Gemini 1.5 Pro
        plan_content = gemini_service.generate_workout_plan(
            name=req.name,
            age=req.age,
            weight=req.weight,
            weight_unit=req.weight_unit or "kg",
            goal=req.goal,
            intensity=req.intensity,
            equipment=req.equipment or "all",
            notes=req.notes or "",
            api_key=client_api_key
        )

        # 3. Save generated plan in SQLite as version 1
        plan_id = database.save_workout_plan(
            user_id=user_id,
            title=plan_content.get("title", f"7-Day {req.goal.title()} Protocol"),
            summary=plan_content.get("summary", ""),
            goal=req.goal,
            intensity=req.intensity,
            plan_data=plan_content,
            version=1,
            model_used=plan_content.get("model_used", gemini_service.MODEL_WORKOUT_GEN)
        )

        # 4. Generate complementary nutrition tip using Gemini Flash
        initial_tip = gemini_service.generate_nutrition_tip(
            goal=req.goal,
            category="nutrition",
            user_info={"name": req.name, "age": req.age, "weight": req.weight, "goal": req.goal},
            api_key=client_api_key
        )
        tip_id = database.save_nutrition_tip(
            goal=req.goal,
            tip_title=initial_tip.get("tip_title", "Nutritional Target"),
            tip_content=initial_tip.get("tip_content", ""),
            action_step=initial_tip.get("action_step", ""),
            category="nutrition",
            user_id=user_id,
            model_used=initial_tip.get("model_used", gemini_service.MODEL_NUTRITION_GEN)
        )

        return {
            "status": "success",
            "message": "7-day workout plan successfully created",
            "user_id": user_id,
            "plan_id": plan_id,
            "version": 1,
            "model_used": plan_content.get("model_used", gemini_service.MODEL_WORKOUT_GEN),
            "plan": plan_content,
            "nutrition_tip": {
                "id": tip_id,
                **initial_tip
            }
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to generate workout plan: {str(e)}")

